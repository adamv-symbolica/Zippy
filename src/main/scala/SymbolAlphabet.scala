package morkl

/** Lossless syntax bridge; no evaluation or callback is used for lowering. */
object SymbolAlphabet:
  def fromPath(p: Path): AlphabetPath[PathValue] = p match
    case Path.Deref(r) => AlphabetPath.Deref(r)
    case Path.Constant(v) => AlphabetPath.Constant(v)
    case Path.Concat(a, b) => AlphabetPath.Concat(fromPath(a), fromPath(b))
    case Path.GroundedPP(x, f) => AlphabetPath.GroundedPP(fromPath(x), f)
    case Path.GroundedSP(x, f) => AlphabetPath.GroundedSP(fromSpace(x), ps => f(SpaceValue(ps)))
  def fromSpace(s: Space): AlphabetSpace[PathValue] = s match
    case Space.Empty => AlphabetSpace.Empty()
    case Space.Call(r, ps, ss) => AlphabetSpace.Call(r, ps.map(fromPath), ss.map(fromSpace))
    case Space.Mention(r) => AlphabetSpace.Mention(r)
    case Space.Singleton(x) => AlphabetSpace.Singleton(fromPath(x))
    case Space.Literal(SpaceValue(v)) => AlphabetSpace.Literal(v)
    case Space.Union(a, b) => AlphabetSpace.Union(fromSpace(a), fromSpace(b))
    case Space.Intersection(a, b) => AlphabetSpace.Intersection(fromSpace(a), fromSpace(b))
    case Space.Subtraction(a, b) => AlphabetSpace.Subtraction(fromSpace(a), fromSpace(b))
    case Space.Restriction(a, b) => AlphabetSpace.Restriction(fromSpace(a), fromSpace(b))
    case Space.Raffination(a, b) => AlphabetSpace.Raffination(fromSpace(a), fromSpace(b))
    case Space.Composition(a, b) => AlphabetSpace.Composition(fromSpace(a), fromSpace(b))
    case Space.Iteration(src, h, r, b) => AlphabetSpace.Iteration(fromSpace(src), h, r, fromSpace(b))
    case Space.Fold(src, init, a, h, r, b, u) => AlphabetSpace.Fold(fromSpace(src), fromPath(init), a, h, r, fromSpace(b), fromPath(u))
    case Space.Fixpoint(init, v, step) => AlphabetSpace.Fixpoint(fromSpace(init), v, fromSpace(step))
    case Space.Wrap(src, x) => AlphabetSpace.Wrap(fromSpace(src), fromPath(x))
    case Space.Unwrap(src, x) => AlphabetSpace.Unwrap(fromSpace(src), fromPath(x))
    case Space.TailsUnion(src) => AlphabetSpace.TailsUnion(fromSpace(src))
    case Space.TailsIntersection(src) => AlphabetSpace.TailsIntersection(fromSpace(src))
    case Space.PrefixClosure(src) => AlphabetSpace.PrefixClosure(fromSpace(src))
    case Space.SuffixClosure(src) => AlphabetSpace.SuffixClosure(fromSpace(src))
    case Space.TailsClosure(src) => AlphabetSpace.TailsClosure(fromSpace(src))
    case Space.GroundedPS(x, f) => AlphabetSpace.GroundedPS(fromPath(x), p => f(p).paths)
    case Space.GroundedSS(x, f) => AlphabetSpace.GroundedSS(fromSpace(x), ps => f(SpaceValue(ps)).paths)
    case Space.Range(src, a, b) => AlphabetSpace.Range(fromSpace(src), a, b)

  def toPath(p: AlphabetPath[PathValue]): Path = p match
    case AlphabetPath.Deref(r) => Path.Deref(r)
    case AlphabetPath.Constant(v) => Path.Constant(v)
    case AlphabetPath.Concat(a, b) => Path.Concat(toPath(a), toPath(b))
    case AlphabetPath.GroundedPP(x, f) => Path.GroundedPP(toPath(x), f)
    case AlphabetPath.GroundedSP(x, f) => Path.GroundedSP(toSpace(x), ps => f(ps.paths))
  def toSpace(s: AlphabetSpace[PathValue]): Space = s match
    case AlphabetSpace.Empty() => Space.Empty
    case AlphabetSpace.Call(r, ps, ss) => Space.Call(r, ps.map(toPath), ss.map(toSpace))
    case AlphabetSpace.Mention(r) => Space.Mention(r)
    case AlphabetSpace.Singleton(x) => Space.Singleton(toPath(x))
    case AlphabetSpace.Literal(v) => Space.Literal(SpaceValue(v))
    case AlphabetSpace.Union(a, b) => Space.Union(toSpace(a), toSpace(b))
    case AlphabetSpace.Intersection(a, b) => Space.Intersection(toSpace(a), toSpace(b))
    case AlphabetSpace.Subtraction(a, b) => Space.Subtraction(toSpace(a), toSpace(b))
    case AlphabetSpace.Restriction(a, b) => Space.Restriction(toSpace(a), toSpace(b))
    case AlphabetSpace.Raffination(a, b) => Space.Raffination(toSpace(a), toSpace(b))
    case AlphabetSpace.Composition(a, b) => Space.Composition(toSpace(a), toSpace(b))
    case AlphabetSpace.Iteration(src, h, r, b) => Space.Iteration(toSpace(src), h, r, toSpace(b))
    case AlphabetSpace.Fold(src, init, a, h, r, b, u) => Space.Fold(toSpace(src), toPath(init), a, h, r, toSpace(b), toPath(u))
    case AlphabetSpace.Fixpoint(init, v, step) => Space.Fixpoint(toSpace(init), v, toSpace(step))
    case AlphabetSpace.Wrap(src, x) => Space.Wrap(toSpace(src), toPath(x))
    case AlphabetSpace.Unwrap(src, x) => Space.Unwrap(toSpace(src), toPath(x))
    case AlphabetSpace.TailsUnion(src) => Space.TailsUnion(toSpace(src))
    case AlphabetSpace.TailsIntersection(src) => Space.TailsIntersection(toSpace(src))
    case AlphabetSpace.PrefixClosure(src) => Space.PrefixClosure(toSpace(src))
    case AlphabetSpace.SuffixClosure(src) => Space.SuffixClosure(toSpace(src))
    case AlphabetSpace.TailsClosure(src) => Space.TailsClosure(toSpace(src))
    case AlphabetSpace.GroundedPS(x, f) => Space.GroundedPS(toPath(x), p => SpaceValue(f(p)))
    case AlphabetSpace.GroundedSS(x, f) => Space.GroundedSS(toSpace(x), ps => SpaceValue(f(ps.paths)))
    case AlphabetSpace.Range(src, a, b) => Space.Range(toSpace(src), a, b)

  def fromRoutine(r: Routine): AlphabetRoutine[PathValue] = AlphabetRoutine(r.name, r.refs, r.mentions, fromSpace(r.body))
  def toRoutine(r: AlphabetRoutine[PathValue]): Routine = Routine(r.name, r.refs, r.mentions, toSpace(r.body))
